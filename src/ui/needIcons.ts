function svg(rows: string[]): string {
  let r = '';
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    const c = KEY[ch];
    if (c) r += `<rect x="${x}" y="${y}" width="1" height="1" fill="${PALETTE[c]}"/>`;
  }));
  return `<svg viewBox="0 0 ${rows[0].length} ${rows.length}" shape-rendering="crispEdges" aria-hidden="true">${r}</svg>`;
}

// NEED_ICONS.hunger[4] is a whole apple, NEED_ICONS.hunger[0] the core.
export const NEED_ICONS = Object.fromEntries(
  Object.entries(ROWS).map(([stat, steps]) => [stat, steps.map(svg)]),
) as Record<keyof PetStats, string[]>;

// Which of the five steps a stat (0-100) shows: 4 from 80 up, 0 under 20.
export const needStep = (value: number): number => Math.max(0, Math.min(4, Math.floor(value / 20)));
