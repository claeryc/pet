// Little pixel-art icons for the Feed/Play lists, drawn as SVG from text
// grids. Each letter is one pixel in a palette colour (see PIXEL_COLORS
// below) and "." is see-through. Placeholder art: swap for real sprites
// later without touching the rest of the UI.

import { PALETTE } from '../render/palette';
import { CURTAINS, WALLPAPERS } from '../render/room';
import { FURNITURE_ART, FURNITURE_COLORS } from '../render/furniture';

const PIXEL_COLORS: Record<string, string> = {
  k: PALETTE.ink,
  w: PALETTE.white,
  r: PALETTE.rose,
  p: PALETTE.pink,
  g: PALETTE.leaf,
  m: PALETTE.mint,
  b: PALETTE.ocean,
  s: PALETTE.sky,
  y: PALETTE.butter,
  c: PALETTE.cocoa,
  o: PALETTE.peach,
  l: PALETTE.lilac,
  v: PALETTE.lavender,
  e: PALETTE.cream,
  u: PALETTE.plum,
};

// Turns a text grid into an SVG string.
// `extra` adds or swaps letters for one icon.
function pixelIcon(rows: string[], extra: Record<string, string> = {}): string {
  const h = rows.length;
  const w = rows[0].length;
  let rects = '';
  rows.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      const color = extra[ch] ?? PIXEL_COLORS[ch];
      if (color) rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${color}"/>`;
    });
  });
  return `<svg viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}

// A wallpaper sample in a frame, drawn with the room's own pattern.
function wallpaperIcon(id: string): string {
  const pattern = WALLPAPERS[id];
  let rects = '';
  for (let y = 0; y < 12; y++) {
    for (let x = 0; x < 12; x++) {
      const edge = x === 0 || y === 0 || x === 11 || y === 11;
      const color = edge ? PALETTE.ink : pattern(x - 1, y - 1, false);
      rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${color}"/>`;
    }
  }
  return `<svg viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}

// A little window with the curtains drawn back (A is the cloth, B the folds).
function curtainsIcon(id: string): string {
  const [main, fold] = CURTAINS[id];
  return pixelIcon(
    [
      'cccccccccccc',
      'ABABkkkkABAB',
      'ABABssssABAB',
      'ABABswssABAB',
      'ABABssssABAB',
      'ABABkkkkABAB',
      'ABABssssABAB',
      'ABABsssmABAB',
      'ABABssmmABAB',
      'ABABkkkkABAB',
      'BBBB....BBBB',
      '............',
    ],
    { A: main, B: fold },
  );
}

// A piece of furniture, as it stands in the room, centred in a square.
function furnitureIcon(id: string): string {
  const rows = FURNITURE_ART[id];
  const size = Math.max(rows.length, rows[0].length);
  const left = Math.floor((size - rows[0].length) / 2);
  const top = Math.floor((size - rows.length) / 2);
  const pad = '.'.repeat(size);
  const square = [
    ...Array<string>(top).fill(pad),
    ...rows.map((r) => '.'.repeat(left) + r + '.'.repeat(size - left - r.length)),
    ...Array<string>(size - top - rows.length).fill(pad),
  ];
  return pixelIcon(square, FURNITURE_COLORS);
}

